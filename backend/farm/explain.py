"""Человеческое объяснение падения шага.

Чистый модуль: строка в строку, без adb и файлов. Сообщения бросают
farm/context.py и runner, здесь они превращаются в «что случилось и что делать».
Ключевое различие — таймаут (ждали и не дождались: экран мог быть медленным)
против настоящего отказа (не то устройство, не тот экран, сломанный блок).
"""
from __future__ import annotations

import re

TIMEOUT, NOT_FOUND, WRONG_SCREEN, DEVICE, BLOCK, RETRIES, OTHER = (
    "timeout", "not_found", "wrong_screen", "device", "block", "retries", "other")

_RULES = [
    (re.compile(r"не найден элемент (.+?) за ([\d.]+) с"), TIMEOUT,
     "Элемент не появился за {1} с",
     "Экран мог не дорисоваться или селектор устарел. Откройте кадр падения: "
     "если элемент виден — поправьте селектор шага или добавьте запасной слой "
     "(текст, картинка). Если экрана ещё нет — увеличьте ожидание."),
    (re.compile(r"цель не найдена ни одним слоем"), NOT_FOUND,
     "Цель не найдена ни одним слоем поиска",
     "Селектор, текст, картинка и точка промахнулись разом — на экране, "
     "скорее всего, другое состояние. Смотрите кадр падения и предложенные "
     "ремонтом замены."),
    (re.compile(r"ожидал экран «(.+?)», вижу (\S+): \[(.*)\]"), WRONG_SCREEN,
     "Не тот экран: ждали «{0}», открыто {1}",
     "На экране: {2}. Если это штатный вариант — добавьте ветку в развилку "
     "или отвод; если сбой — проверьте предыдущий шаг."),
    (re.compile(r"uiautomator2 недоступен|устройство недоступно|offline|"
                r"device .*not found|no devices", re.I), DEVICE,
     "Устройство не отвечает",
     "Проверьте кабель и «Отладку по USB», переподключите устройство в ферме."),
    (re.compile(r"блок «(.+?)»"), BLOCK,
     "Проблема с блоком «{0}»",
     "Блок не найден, зациклен или упал внутри. Откройте его в конструкторе."),
    (re.compile(r"не удалось за (\d+) попыт"), RETRIES,
     "Шаг не удался за {0} попыток",
     "Повтор не помог — причина устойчивая. Смотрите строки попыток в журнале."),
]


def explain(message: str) -> dict:
    """{kind, title, hint, timeout}: по сообщению исключения."""
    text = str(message or "")
    for pattern, kind, title, hint in _RULES:
        m = pattern.search(text)
        if m:
            g = m.groups()
            return {"kind": kind, "timeout": kind == TIMEOUT,
                    "title": title.format(*g), "hint": hint.format(*g)}
    return {"kind": OTHER, "timeout": False,
            "title": text.splitlines()[0][:200] if text else "Задача упала без сообщения",
            "hint": "Подробности — в журнале и артефактах задачи."}
