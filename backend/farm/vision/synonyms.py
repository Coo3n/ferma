"""Синонимы типовых кнопок ru/en: на MIUI «Разрешить», на Samsung «Allow».

Без них текстовый селектор, записанный на одном устройстве, промахивается на
устройстве с другой локалью.
"""
from __future__ import annotations

# OCR путает кириллицу с визуально неотличимой латиницей: «Вoйти» с латинской
# «o» перестаёт совпадать с «Войти». Таблицу гомоглифов и нормализацию держим
# здесь в одном месте: и resolve.match_text, и expand() ниже обязаны приводить
# текст к одному алфавиту одинаковым способом, иначе точные совпадения (в том
# числе через синонимы) развалятся.
HOMOGLYPHS = str.maketrans({
    "a": "а", "e": "е", "o": "о", "p": "р", "c": "с", "y": "у", "x": "х",
})


def normalize(text: str) -> str:
    """Casefold, схлопнуть пробелы, привести гомоглифы к кириллице."""
    return " ".join((text or "").casefold().translate(HOMOGLYPHS).split())


PAIRS = [
    ("разрешить", "allow"), ("далее", "next"), ("продолжить", "continue"),
    ("пропустить", "skip"), ("принять", "accept"), ("ок", "ok"),
    ("готово", "done"), ("войти", "log in"), ("отмена", "cancel"),
    ("закрыть", "close"), ("начать", "get started"), ("понятно", "got it"),
]

_INDEX: dict[str, set[str]] = {}
for _a, _b in PAIRS:
    # Ключи индекса — через normalize(): английское "allow" содержит a/o,
    # которые normalize() переводит в кириллицу, и без этого запрос "ALLOW"
    # не найдёт пару. Сами значения храним как есть (без перевода гомоглифов)
    # — это обычные слова языка, а не текст с экрана; сравнивать их с текстом
    # экрана через гомоглифы будет match_text, применяя normalize() к обеим
    # сторонам непосредственно перед сравнением.
    _INDEX.setdefault(normalize(_a), {_a}).add(_b)
    _INDEX.setdefault(normalize(_b), {_b}).add(_a)


def expand(text: str) -> set[str]:
    """Нормализованный текст плюс его синонимы на другом языке."""
    key = normalize(text)
    return set(_INDEX.get(key, {key}))
